class PartyAlias < ApplicationRecord
  ALIAS_TYPES = %w[maiden_name former_name nickname trade_name former_company_name abbreviation other_name].freeze

  belongs_to :party, inverse_of: :aliases

  normalizes :name, with: ->(value) { value.squish }

  validates :name, presence: true, length: { maximum: 255 }
  validates :alias_type, inclusion: { in: ALIAS_TYPES }
end
